import {readFileSync,writeFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {CARD_CATALOG} from '../src/card-battle-data.mjs';
import {CARD_CULTURES} from '../src/card-battle-cultures.mjs';

const evidence=JSON.parse(readFileSync(new URL('../docs/card-battle-person-cultural-evidence.json',import.meta.url),'utf8'));
const catalog=CARD_CATALOG.cards.filter(d=>d.type==='general');
assert.equal(evidence.people.length,catalog.length);
assert.equal(new Set(evidence.people.map(p=>p.personId)).size,catalog.length);
const rows={};
for(const p of evidence.people){
 const d=catalog.find(d=>d.person_id===p.personId);
 assert.equal(d?.name,p.name,`Unknown or renamed ID ${p.personId}`);
 const confirmed=p.cultureStatus==='regional-evidence-reviewed';
 assert.ok(confirmed||p.cultureStatus==='reviewed-identity-unresolved',`Unreviewed ${p.personId}`);
 assert.equal(confirmed,Boolean(d.source.historicalVerified),`Original identity must remain unresolved: ${p.personId}`);
 if(confirmed){assert.ok(CARD_CULTURES[p.culture],p.personId);assert.ok(p.evidence.length&&p.region&&p.period,p.personId);}
 else{assert.equal(p.culture,null);assert.ok(p.reviewConclusion,p.personId);}
 rows[p.personId]={culture:confirmed?p.culture:null,status:p.cultureStatus,period:confirmed?p.period:null,region:confirmed?p.region:null,identityStatus:p.identityStatus,conclusion:confirmed?p.mappingRationale:p.reviewConclusion,evidence:p.evidence.map(x=>x.url??x.localPath)};
}
const output=`// Generated by scripts/sync-card-person-cultures.mjs from the reviewed evidence register.\n// Culture keys are broad game art pools, never ethnicity or costume certification.\nconst rows=${JSON.stringify(rows,null,2)};\nexport const PERSON_CULTURE_REVIEWS=Object.freeze(Object.fromEntries(Object.entries(rows).map(([id,row])=>[id,Object.freeze({...row,evidence:Object.freeze(row.evidence)})])));\nexport function personCultureReview(id){const row=PERSON_CULTURE_REVIEWS[id];return row?{...row,evidence:[...row.evidence]}:null;}\n`;
writeFileSync(new URL('../src/card-battle-person-culture-data.mjs',import.meta.url),output);
console.log(`Synced ${Object.keys(rows).length} ID reviews; ${Object.values(rows).filter(p=>p.culture).length} culture mappings; original identities retained.`);
