"""Read generated alpha silhouettes into SVG frame/clip metadata; never alter pixels."""
import json
from collections import deque
from pathlib import Path
import numpy as np
from PIL import Image

root = Path(__file__).resolve().parents[1]
result = {}
for path in sorted((root / 'assets').glob('war-general-mounted-*-v2.png')):
    image = Image.open(path)
    width, height = image.size
    # Four-pixel sampling is subpixel at the game's displayed size.
    step = 4
    alpha = np.array(image.getchannel('A').resize((width // step, height // step)))
    remaining = alpha > 80
    h, w = remaining.shape
    parts = []
    for y in range(h):
        for x in range(w):
            if not remaining[y, x]:
                continue
            pending, points = [(x, y)], []
            remaining[y, x] = False
            while pending:
                a, b = pending.pop()
                points.append((a, b))
                for c, d in [(a+1,b), (a-1,b), (a,b+1), (a,b-1)]:
                    if 0 <= c < w and 0 <= d < h and remaining[d,c]:
                        remaining[d,c] = False
                        pending.append((c,d))
            if len(points) > 500:
                parts.append(points)
    if len(parts) != 8:
        # A weapon tip may touch the next pose. Find the eight body cores,
        # then assign the original alpha pixels by connected distance.
        mask = alpha > 80
        core = mask.copy()
        for dy in [-1,0,1]:
            for dx in [-1,0,1]:
                core &= np.roll(np.roll(mask,dy,0),dx,1)
        seeds = []
        for y,x in zip(*np.where(core)):
            if not core[y,x]: continue
            pending, points = [(x,y)], []
            core[y,x] = False
            while pending:
                a,b = pending.pop()
                points.append((a,b))
                for c,d in [(a+1,b),(a-1,b),(a,b+1),(a,b-1)]:
                    if 0 <= c < w and 0 <= d < h and core[d,c]:
                        core[d,c] = False
                        pending.append((c,d))
            if len(points)>300: seeds.append(points)
        if len(seeds)!=8:
            print(f'NEEDS REPAIR {path.name}: expected 8 body cores, found {len(seeds)}')
            continue
        labels = np.full((h,w),-1,dtype=int)
        pending = deque()
        for i,points in enumerate(seeds):
            for x,y in points:
                labels[y,x] = i
                pending.append((x,y))
        while pending:
            x,y = pending.popleft()
            for c,d in [(x+1,y),(x-1,y),(x,y+1),(x,y-1)]:
                if 0 <= c < w and 0 <= d < h and mask[d,c] and labels[d,c]<0:
                    labels[d,c] = labels[y,x]
                    pending.append((c,d))
        centers = [(sum(x for x,y in p)/len(p),sum(y for x,y in p)/len(p)) for p in seeds]
        for y,x in zip(*np.where(mask & (labels<0))):
            labels[y,x] = min(range(8),key=lambda i:(x-centers[i][0])**2+(y-centers[i][1])**2)
        parts = [[(int(x),int(y)) for y,x in zip(*np.where(labels==i))] for i in range(8)]
    parts.sort(key=lambda p: (int(sum(y for x,y in p)/len(p)/h*4), min(x for x,y in p)))
    figures = []
    for points in parts:
        left, top = min(x for x,y in points)*step, min(y for x,y in points)*step
        right, bottom = (max(x for x,y in points)+1)*step, (max(y for x,y in points)+1)*step
        feet = [x*step for x,y in points if y*step > bottom-40]
        anchor = round(float(np.median(feet)))
        # Clip only this connected silhouette, with padding for antialiased edges.
        rows = {}
        for x,y in points:
            for dy in [-1,0,1]:
                rows.setdefault(y+dy, set()).update([x-1,x,x+1])
        commands = []
        for y,xs in sorted(rows.items()):
            xs = sorted(xs)
            start = end = xs[0]
            for x in xs[1:] + [10**9]:
                if x > end+1:
                    commands.append(f'M{start*step} {y*step}h{(end-start+1)*step}v{step}h{-((end-start+1)*step)}z')
                    start = x
                end = x
        figures.append(dict(left=left,top=top,right=right,bottom=bottom,anchor=anchor,clip=''.join(commands)))
    half = max(max(f['anchor']-f['left'], f['right']-f['anchor']) for f in figures)+12
    frame_height = max(f['bottom']-f['top'] for f in figures)+24
    frames = [[f['anchor']-half, f['bottom']-frame_height+8, half*2,frame_height] for f in figures]
    result['general-'+path.stem.removeprefix('war-general-mounted-').removesuffix('-v2')] = dict(
        revision=2,mounted=True,width=width,height=height,displayWidth=round(128*half*2/frame_height),displayHeight=128,
        walk=frames[:4],attack=frames[4:],clipPaths={','.join(map(str,frame)): f['clip'] for frame,f in zip(frames,figures)})
target = root / 'src/battle-general-frames.mjs'
target.write_text('// Measured alpha silhouettes; generated by scripts/measure-general-atlases.py.\nexport const generalFrames='+json.dumps(result,separators=(',',':'))+';\n')
print(f'Measured {len(result)} atlases ({target.stat().st_size} bytes)')
